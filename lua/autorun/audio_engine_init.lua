--[[
	Audio Engine loader.

	The engine sound (lua/audio_engine/) is the core and works on its own. Everything else is an
	optional module in its own folder, loaded after it when the folder is there: delete a folder to
	drop that module, nothing else. The core never calls a module; modules use the core's functions
	and its audio_engine/* hooks.
	  lua/audio_engine_handling/  handling assists, PERP physics on the test script, the tuning
	                              menu's acceleration / top speed, speed limiter (server)
	  lua/audio_engine_hud/       the speed / rpm HUD (client)
	  lua/audio_engine_debug/     debug tools (not for the final addon)
]]
AUDIO_ENGINE = AUDIO_ENGINE or {}

local function loadModule(folder, sharedFiles, clientFiles, serverFiles)
	if SERVER then
		for _, fileName in ipairs(sharedFiles) do AddCSLuaFile(folder .. fileName) end
		for _, fileName in ipairs(clientFiles) do AddCSLuaFile(folder .. fileName) end
	end
	for _, fileName in ipairs(sharedFiles) do include(folder .. fileName) end
	for _, fileName in ipairs(SERVER and serverFiles or clientFiles) do include(folder .. fileName) end
end

-- whether an optional module's folder is there (looked up by one file it always has)
local function hasModule(folder, fileName)
	return file.Exists(folder .. fileName, "LUA")
end

-- the core: engine sound, ignition, stock sound muting, police lights, passenger seats, tuning menu
-- (cl_baked.lua: generated by dev/baker, what the pre-generated sounds in sound/audio_engine/ are)
loadModule("audio_engine/",
	{ "sh_config.lua", "sh_presets.lua", "sh_drivetrain.lua", "sh_carlist.lua", "sh_perp.lua", "sh_police.lua" },
	{ "cl_baked.lua", "cl_synth.lua", "cl_soundbank.lua", "cl_engine.lua", "cl_menu.lua", "cl_police.lua" },
	{ "sv_engine.lua", "sv_police.lua", "sv_seats.lua" })

-- handling (server only). sv_perp_physics.lua is generated: PERP's base-script physics per car
if hasModule("audio_engine_handling/", "sv_handling.lua") then
	loadModule("audio_engine_handling/", {}, {},
		{ "sv_perp_physics.lua", "sv_handling.lua", "sv_stability.lua", "sv_cruise.lua" })
end

-- the speed / rpm HUD (client only; the server only sends it)
if hasModule("audio_engine_hud/", "cl_hud.lua") then
	loadModule("audio_engine_hud/", {}, { "cl_hud.lua" }, {})
end

-- the debug tools (script, gearing and rev editors, handling switches, profiler; superadmins,
-- audio_engine_debug). Their handling pages need the handling module
local debugFolder = "audio_engine_debug/"
if hasModule(debugFolder, "sh_debug.lua") then
	if SERVER then
		for _, fileName in ipairs({ "sh_kv.lua", "sh_debug.lua", "cl_debug.lua", "cl_handling_overlay.lua", "cl_perf.lua" }) do AddCSLuaFile(debugFolder .. fileName) end
	end
	include(debugFolder .. "sh_kv.lua")
	include(debugFolder .. "sh_debug.lua")
	include(debugFolder .. (SERVER and "sv_debug.lua" or "cl_debug.lua"))
	-- the handling values pinned / changed in the menu on screen in the car, edited with C held
	if CLIENT then include(debugFolder .. "cl_handling_overlay.lua") end
	-- the profiler (audio_engine_perf, audio_engine_perf_hud): measures nothing until it's turned on
	include(debugFolder .. (SERVER and "sv_perf.lua" or "cl_perf.lua"))
end
